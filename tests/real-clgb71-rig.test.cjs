const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {buildRig,checkSetup}=require('../engine/rig.js');

test('approved clgb71 PSD: all 38 original layers preserve their setup pose and draw order',t=>{
  const path=process.env.PSD_LAYER_MANIFEST;
  if(!path){
    t.skip('Requires an approved PSD manifest generated by the live-source CI job');
    return;
  }
  const manifest=JSON.parse(fs.readFileSync(path,'utf8'));
  assert.equal(manifest.source_sha256,'7adee866547a3b3cc9838b655cf70865980c5dba00313373cbf903fed776c7b2');
  assert.equal(manifest.source_bytes,4485543);
  assert.deepEqual(manifest.canvas,{width:918,height:657});
  assert.equal(manifest.contains_source_pixels,false);
  assert.equal(manifest.layers.length,38);
  assert.deepEqual(manifest.layers.map(x=>x.order),Array.from({length:38},(_,i)=>i));
  const before=JSON.stringify(manifest.layers);
  // Do not invent missing anatomy: required two-hand IK must fail closed if
  // artwork cannot establish both limbs; optional IK can retain available ones.
  const plan={rig:{armIK:{enabled:true,bothHands:true,arms:['left','right'],required:false}}};
  const rig=buildRig(manifest.layers,plan,manifest.canvas);
  assert.equal(JSON.stringify(manifest.layers),before,'never mutate source layer metadata');
  assert.equal(rig.skeleton.skeleton.spine,'4.3.26');
  assert.deepEqual(rig.skeleton.slots.map(s=>s.name),manifest.layers.map(l=>l.name));
  assert.equal(rig.skeleton.slots.length,38);
  assert.equal(rig.invariants.ok,true);
  assert.ok(rig.invariants.maxPositionError<1e-6);
  assert.equal(checkSetup(rig.skeleton,rig.context).ok,true);
  assert.ok(rig.skeleton.constraints.length<=2);
  for(const c of rig.skeleton.constraints)assert.equal(c.type,'ik');
  for(const name of ['pistol','pistol--front','finger','hand-right','torso','face','Eyes','Sombrero'])
    assert.ok(rig.context.layerBindings[name],name+' missing from real PSD rig');
  const meshAttachments=Object.values(rig.skeleton.skins[0].attachments)
    .flatMap(slot=>Object.values(slot)).filter(a=>a.type==='mesh');
  assert.ok(meshAttachments.length>=1,'weighted hand mesh must be retained');
  for(const a of meshAttachments){
    assert.ok(Array.isArray(a.edges)&&a.edges.length>0&&a.edges.length%2===0,
      'Spine Editor import requires Nonessential edges');
    const expected=new Set();
    for(let i=0;i<a.triangles.length;i+=3){
      const t=a.triangles;
      for(const [x,y] of [[t[i],t[i+1]],[t[i+1],t[i+2]],[t[i+2],t[i]]])
        expected.add([Math.min(x,y),Math.max(x,y)].join(':'));
    }
    const actual=new Set();
    for(let i=0;i<a.edges.length;i+=2){
      const x=a.edges[i],y=a.edges[i+1];
      assert.equal(x%2,0,'edge endpoint must use even UV offset');
      assert.equal(y%2,0,'edge endpoint must use even UV offset');
      assert.ok(x>=0&&x<a.uvs.length&&y>=0&&y<a.uvs.length);
      actual.add([Math.min(x,y)/2,Math.max(x,y)/2].join(':'));
    }
    assert.deepEqual(actual,expected,'mesh editable edges must match triangulation');
    assert.equal(actual.size,a.edges.length/2,'no duplicate mesh edges');
  }
  // This PSD has a contiguous held fan between the right finger and hand.
  // A shoot-up pose must not leave that fan floating while the right hand moves.
  for(let i=1;i<=9;i++)
    assert.equal(rig.context.layerBindings['card-'+i].parentBone,rig.context.arms.right.handBone,
      'held fan card must follow the right-hand IK wrist');
  assert.equal(rig.context.layerBindings['shadow-card'].parentBone,rig.context.arms.right.handBone);
  for(const name of ['card-22','card-20','card-17'])
    assert.equal(rig.context.layerBindings[name].parentBone,'cards_root',
      'independent flying cards must remain detachable');
  assert.equal(rig.context.heldCardNames.length,10);
  const gun=rig.context.layerBindings['pistol--front'];
  assert.equal(gun.role,'gun','weapon overlay must not follow head');
});
